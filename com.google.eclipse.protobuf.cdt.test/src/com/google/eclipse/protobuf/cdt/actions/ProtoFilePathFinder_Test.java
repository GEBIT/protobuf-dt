package com.google.eclipse.protobuf.cdt.actions;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNull;

import org.junit.Test;

public class ProtoFilePathFinder_Test {
  private final ProtoFilePathFinder finder = new ProtoFilePathFinder();
  private static final String GENERATED = "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n";

  @Test public void should_find_legacy_two_line_source_banner() {
    assertEquals("legacy/message.proto", finder.findProtoFilePathIn(
        GENERATED + "// source: legacy/message.proto\n#ifndef MESSAGE_H\n").toPortableString());
  }

  @Test public void should_find_current_three_line_source_banner() {
    assertEquals("google/protobuf/descriptor.proto", finder.findProtoFilePathIn(GENERATED
        + "// NO CHECKED-IN PROTOBUF GENCODE\n// source: google/protobuf/descriptor.proto\n"
        + "#ifndef DESCRIPTOR_H\n").toPortableString());
  }

  @Test public void should_scan_leading_blank_and_comment_lines() {
    assertEquals("demo/main.proto", finder.findProtoFilePathIn(GENERATED
        + "\n// Additional generator notice\n  // Another notice\n\n// source: demo/main.proto\n")
        .toPortableString());
  }

  @Test public void should_reject_nongenerated_and_missing_or_empty_sources() {
    assertNull(finder.findProtoFilePathIn("// source: demo/main.proto\n"));
    assertNull(finder.findProtoFilePathIn(" " + GENERATED + "// source: demo/main.proto\n"));
    assertNull(finder.findProtoFilePathIn(GENERATED + "// No source here\n#ifndef HEADER\n"));
    assertNull(finder.findProtoFilePathIn(GENERATED + "// source: \n"));
    assertNull(finder.findProtoFilePathIn(GENERATED + "// source:    \n"));
    assertNull(finder.findProtoFilePathIn(GENERATED + "#ifndef HEADER\n// source: too/late.proto\n"));
    assertNull(finder.findProtoFilePathIn((String) null));
  }
}
